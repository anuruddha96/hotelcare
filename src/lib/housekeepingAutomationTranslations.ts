export type HousekeepingAutomationTextKey = keyof typeof translations.en;

export function getHousekeepingAutomationLanguage(): HousekeepingAutomationLanguage {
  if (typeof window === 'undefined') return 'en';
  const stored = [
    window.localStorage.getItem('language'),
    window.localStorage.getItem('hotelcare_language'),
    window.localStorage.getItem('selectedLanguage'),
    document.documentElement.lang,
    window.navigator.language,
  ].find(Boolean) || 'en';
  const code = stored.toLowerCase().split('-')[0] as HousekeepingAutomationLanguage;
  return code in translations ? code : 'en';
}

export function housekeepingAutomationText(
  key: HousekeepingAutomationTextKey,
  language: HousekeepingAutomationLanguage = getHousekeepingAutomationLanguage(),
): string {
  return translations[language]?.[key] ?? translations.en[key];
}
