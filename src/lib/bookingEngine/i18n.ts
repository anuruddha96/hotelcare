const DICTS: Record<BookingLang, Dict> = { en, hu, de, es, it, fr };

export const AMENITY_KEYS = [
  'wifi', 'ac', 'tv', 'minibar', 'safe', 'kettle', 'coffee', 'hairdryer', 'shower', 'bathtub', 'balcony', 'city_view',
  'desk', 'soundproof', 'bathrobe', 'non_smoking', 'accessible', 'family', 'kitchenette', 'washing_machine',
] as const;

export function isBookingLang(value: unknown): value is BookingLang {
  return typeof value === 'string' && (BOOKING_LANGS as readonly string[]).includes(value);
}

/** Translate with {placeholder} values; falls back to English, then the key. */
export function bookingT(lang: BookingLang, key: string, values: Record<string, string | number> = {}): string {
  const template = DICTS[lang]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

/** "{n} night" / "{n} nights" style plural for the keys that have One/Many forms. */
export function bookingPlural(lang: BookingLang, base: 'adults' | 'children' | 'rooms' | 'nights', n: number): string {
  return bookingT(lang, `${base}${n === 1 ? 'One' : 'Many'}`, { n });
}

export function missingTranslations(): Array<{ lang: BookingLang; key: string }> {
  const missing: Array<{ lang: BookingLang; key: string }> = [];
  for (const lang of BOOKING_LANGS) {
    for (const key of Object.keys(en)) if (!(key in DICTS[lang])) missing.push({ lang, key });
  }
  return missing;
}
