export function useChannelCopy(): { t: ChannelCopy; hu: boolean; locale: string } {
  const { language } = useTranslation();
  const isHu = language === "hu";
  return { t: isHu ? hu : en, hu: isHu, locale: isHu ? "hu-HU" : "en-GB" };
}
